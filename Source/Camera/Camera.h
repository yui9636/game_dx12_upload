#pragma once

#include <DirectXMath.h>

// =========================================================
// Camera
// ---------------------------------------------------------
// エンジン全体で共有するシンプルなカメラクラスです。
// ビュー行列、射影行列、カメラの向きベクトルを保持します。
// 現在はシングルトンとして利用されます。
// =========================================================
class Camera
{
private:
	// 以前は外部生成を禁止する想定だった名残です。
	//Camera() {}
	//~Camera() {}
public:
	// =========================================================
	// カメラの唯一のインスタンスを取得します。
	// =========================================================
	static Camera& Instance()
	{
		static Camera camera;
		return camera;
	}

	// =========================================================
	// 注視点を指定してビュー行列を更新します。
	// eye   : カメラ位置
	// focus : 注視点
	// up    : 上方向ベクトル
	// =========================================================
	void SetLookAt(const DirectX::XMFLOAT3& eye, const DirectX::XMFLOAT3& focus, const DirectX::XMFLOAT3& up);

	// =========================================================
	// 透視投影行列を更新します。
	// fovY   : 縦方向の視野角
	// aspect : アスペクト比
	// nearZ  : ニアクリップ距離
	// farZ   : ファークリップ距離
	// =========================================================
	void SetPerspectiveFov(float fovY, float aspect, float nearZ, float farZ);

	// =========================================================
	// ビュー行列を取得します。
	// =========================================================
	const DirectX::XMFLOAT4X4& GetView() const { return view; }

	// =========================================================
	// 射影行列を取得します。
	// =========================================================
	const DirectX::XMFLOAT4X4& GetProjection() const { return projection; }

	// =========================================================
	// カメラ位置を取得します。
	// =========================================================
	const DirectX::XMFLOAT3& GetEye() const { return eye; }

	// =========================================================
	// カメラの注視点を取得します。
	// =========================================================
	const DirectX::XMFLOAT3& GetFocus() const { return focus; }

	// =========================================================
	// カメラの上方向ベクトルを取得します。
	// =========================================================
	const DirectX::XMFLOAT3& GetUp() const { return up; }

	// =========================================================
	// カメラの前方向ベクトルを取得します。
	// =========================================================
	const DirectX::XMFLOAT3& GetFront() const { return front; }

	// =========================================================
	// カメラの右方向ベクトルを取得します。
	// =========================================================
	const DirectX::XMFLOAT3& GetRight() const { return right; }

	// =========================================================
	// 縦方向の視野角を取得します。
	// =========================================================
	const	float& GetFovY() { return	fovY; }

	// =========================================================
	// アスペクト比を取得します。
	// =========================================================
	const	float& GetAspect() { return	aspect; }

	// =========================================================
	// ニアクリップ距離を取得します。
	// =========================================================
	const	float& GetNearZ() { return	nearZ; }

	// =========================================================
	// ファークリップ距離を取得します。
	// =========================================================
	const	float& GetFarZ() { return	farZ; }

private:
	// ビュー行列です。
	DirectX::XMFLOAT4X4		view;

	// 射影行列です。
	DirectX::XMFLOAT4X4		projection;

	// カメラのワールド位置です。
	DirectX::XMFLOAT3		eye;

	// カメラが見ている注視点です。
	DirectX::XMFLOAT3		focus;

	// カメラの上方向ベクトルです。
	DirectX::XMFLOAT3		up{ 0.0f, 1.0f, 0.0f };

	// カメラの前方向ベクトルです。
	DirectX::XMFLOAT3		front{ 0.0f, 0.0f, 1.0f };

	// カメラの右方向ベクトルです。
	DirectX::XMFLOAT3		right{ 1.0f, 0.0f, 0.0f };

	// 縦方向の視野角です。
	float fovY = DirectX::XM_PIDIV4;

	// 画面のアスペクト比です。
	float aspect = 1.777f;

	// ニアクリップ距離です。
	float nearZ = 0.1f;

	// ファークリップ距離です。
	float farZ = 100000.0f;
};
